import assert from 'node:assert/strict';
import {createEntry,dayStart,addDays,fixedSegments,planWeek,missed,retryEntry,deferForIllness,validUrl,normalize,historyLabel} from '../core.js';
const today=dayStart(new Date(2026,10,19,12).getTime());
const now=today+12*3600000;
const event=createEntry({fixed:true,title:'授業ではない一回の予定',startMs:today+16*3600000,endMs:today+17*3600000});
const task=createEntry({fixed:false,title:'提出',deadlineMs:today+10*3600000,estimateMin:60});
assert.ok(missed(task,now));
const moved=retryEntry(task,[event,task],now);
assert.equal(moved.deadlineMs,task.deadlineMs,'external deadline must not change');
assert.ok(moved.replanTargetMs>now);
assert.ok(planWeek([moved],today,{fromHour:8,toHour:22,chunk:60},now).some(x=>x.generated));
const altered=deferForIllness([event,task],now,1);
assert.equal(altered.length,2);
assert.ok(altered.find(x=>x.syncId===event.syncId).startMs>=addDays(today,1));
assert.equal(altered.find(x=>x.syncId===task.syncId).deadlineMs,task.deadlineMs);
assert.ok(historyLabel(altered[0]));
const weekly=createEntry({fixed:true,weekly:true,title:'毎週授業',startMs:addDays(today,-3)+9*3600000,endMs:addDays(today,-3)+10*3600000});
const thisWeek=addDays(today,4);
const batch=deferForIllness([weekly],thisWeek+8*3600000,1);
assert.equal(batch.length,2,'the affected weekly occurrence is skipped and a candidate is created');
const modified=batch.find(x=>x.syncId===weekly.syncId);
assert.ok(modified.skippedDays);
assert.equal(fixedSegments([modified],thisWeek,addDays(thisWeek,1)).length,0);
assert.equal(fixedSegments([modified],addDays(thisWeek,7),addDays(thisWeek,8)).length,1,'next week remains intact');
assert.equal(deferForIllness([modified,...batch.filter(x=>x.syncId!==weekly.syncId)],thisWeek+8*3600000,1).filter(x=>x.title.includes('振替候補')).length,0,'no duplicate sick recurrence');
assert.ok(validUrl('https://example.com/a?b=1'));
assert.equal(validUrl('javascript:alert(1)'),false);
assert.equal(normalize({...event,url:'https://example.com',resumeAfterMs:123}).url,'https://example.com');
console.log('Recovery/illness/URL tests passed');