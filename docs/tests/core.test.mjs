import assert from 'node:assert/strict';
import {createEntry,dayStart,addDays,weekStart,fixedSegments,mergeByRevision,planWeek,toLocalInput,fromLocalInput} from '../core.js';
const monday=weekStart(new Date(2026,10,9,12).getTime());
assert.equal(new Date(monday).getDay(),1);
const start=new Date(2026,10,9,9).getTime();
const lecture=createEntry({fixed:true,weekly:true,startMs:start,endMs:start+90*60000});
const events=fixedSegments([lecture],monday,addDays(monday,21));
assert.equal(events.length,3);assert.equal(events[0].start,start);
assert.equal(fixedSegments([lecture],addDays(monday,-21),monday).length,0);
const later={...lecture,title:'新題名',updatedMs:100};const newer={...lecture,title:'旧題名',updatedMs:80};
assert.equal(mergeByRevision([later],[newer]).upload.length,1);
assert.equal(mergeByRevision([newer],[later]).entries[0].title,'新題名');
const deleted={...lecture,deleted:true,updatedMs:200};assert.equal(mergeByRevision([newer],[deleted]).entries[0].deleted,true);
const value=toLocalInput(start);assert.equal(fromLocalInput(value),start);
const task=createEntry({fixed:false,estimateMin:60,progress:0,deadlineMs:addDays(monday,4)});
const planned=planWeek([lecture,task],monday,{fromHour:8,toHour:19,chunk:60},monday+1000);
assert.ok(planned.some(b=>b.generated));
assert.ok(!planned.some((b,i)=>b.generated&&planned.some((other,j)=>i!==j&&other.entry.syncId!==b.entry.syncId&&other.start<b.end&&other.end>b.start)));
console.log('Core tests passed');
